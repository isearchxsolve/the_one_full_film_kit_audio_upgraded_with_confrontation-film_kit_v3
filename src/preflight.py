#!/usr/bin/env python3
"""Preflight gate: verify environment, GPU, internet, and inputs before rendering.
Fails LOUD with the exact fix. Idempotent — safe to re-run.
"""
import os, sys, json, shutil, subprocess

OK, WARN, ERR = "[ok]", "[warn]", "[FAIL]"

def _has(cmd):
    return shutil.which(cmd) is not None

def check_gpu():
    if not _has("nvidia-smi"):
        return ERR, "No nvidia-smi. Set Accelerator = GPU T4 x2 in Session Options."
    out = subprocess.run(["nvidia-smi", "--query-gpu=name,memory.total",
                          "--format=csv,noheader"], capture_output=True, text=True).stdout.strip()
    n = len([l for l in out.splitlines() if l.strip()])
    if n < 2:
        return WARN, f"Only {n} GPU visible. Kit runs, but 2x T4 recommended. ({out})"
    return OK, f"{n} GPUs: {out.replace(chr(10), ' | ')}"

def check_internet():
    try:
        import urllib.request
        urllib.request.urlopen("https://huggingface.co", timeout=10)
        return OK, "Internet reachable."
    except Exception as e:
        return ERR, ("No internet. In Kaggle you must verify phone + identity, then "
                     f"toggle Internet = On in Session Options. ({e})")

def check_inputs(root):
    msgs = []
    cfg_name = os.environ.get("KIT_CONFIG", "config.yaml")
    try:
        import yaml as _yaml
        _cfg = _yaml.safe_load(open(os.path.join(root, cfg_name)))
    except Exception:
        _cfg = {}
    _forge = (_cfg.get("character_forge") or {})
    if _forge.get("enabled"):
        # Forged protagonist(s): GENERATED by the forge; no photos required.
        for t in _forge.get("targets", []):
            fd = os.path.join(root, "refs", t, "face")
            has = os.path.isdir(fd) and any(f.lower().endswith((".jpg", ".jpeg", ".png", ".webp")) for f in os.listdir(fd))
            msgs.append((OK, f"{t}: forged reference set present." if has else f"{t}: will be generated by the character forge (no photos needed)."))
        # Hybrid (THE ONE): real characters still need photos for the beautiful arc.
        for name in (_cfg.get("real_characters") or []):
            found = 0
            for d in (name, f"{name}_young", f"{name}_40s"):
                base = os.path.join(root, "refs", d)
                for sub in ("face", "body", "costume"):
                    p = os.path.join(base, sub)
                    if os.path.isdir(p):
                        for _, _, files in os.walk(p):
                            found += len([f for f in files if f.lower().endswith((".jpg", ".jpeg", ".png", ".webp"))])
                inbox = os.path.join(base, "_inbox")
                if os.path.isdir(inbox):
                    found += len([f for f in os.listdir(inbox) if f.lower().endswith((".jpg", ".jpeg", ".png", ".webp"))])
            msgs.append((OK if found else ERR,
                         f"{name}: {found} real photos filed." if found else f"{name}: no photos found. Drop images in refs/{name}/_inbox/."))
        _script = (_cfg.get("paths") or {}).get("script", "script/lines.csv")
        sp = os.path.join(root, _script)
        msgs.append((OK if os.path.exists(sp) else ERR,
                     f"{_script} present." if os.path.exists(sp) else f"Missing {_script}."))
        return msgs
    for name in ("kunal", "gunja"):
        d = os.path.join(root, "refs", name)
        inbox = os.path.join(d, "_inbox")
        picked = []
        for sub in ("face", "body", "costume"):
            p = os.path.join(d, sub)
            if os.path.isdir(p):
                for base, _, files in os.walk(p):
                    picked += [f for f in files if f.lower().endswith((".jpg",".jpeg",".png",".webp"))]
        inbox_n = 0
        if os.path.isdir(inbox):
            inbox_n = len([f for f in os.listdir(inbox)
                           if f.lower().endswith((".jpg",".jpeg",".png",".webp"))])
        if picked:
            msgs.append((OK, f"{name}: {len(picked)} photos already filed."))
        elif inbox_n:
            msgs.append((OK, f"{name}: {inbox_n} photos in _inbox/ (culler will file them)."))
        else:
            msgs.append((ERR, f"{name}: no photos found. Drop images in refs/{name}/_inbox/."))
    lines = os.path.join(root, "script", "lines.csv")
    msgs.append((OK if os.path.exists(lines) else ERR,
                 "script/lines.csv present." if os.path.exists(lines) else "Missing script/lines.csv."))
    return msgs

def main():
    root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    results = [check_gpu(), check_internet(), *check_inputs(root)]
    print("== PREFLIGHT ==")
    fatal = False
    for status, msg in results:
        print(f"  {status} {msg}")
        if status == ERR:
            fatal = True
    if fatal:
        print("\nPreflight FAILED — fix the [FAIL] items above, then re-run.")
        sys.exit(1)
    print("\nPreflight passed.")

if __name__ == "__main__":
    main()
